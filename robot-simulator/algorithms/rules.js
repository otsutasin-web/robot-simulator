export function evaluateRules(pairDir,s) {

    // ============================================
    // 回りたい
    // ============================================

    if (pairDir == 0
        && s[0] == 2
        && s[1] == 2
        && s[2] == 0
        && s[3] == 0
        && s[4] == 0
        && s[5] == 0
        && s[6] == 0) {
        return 2;
    }

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 0
        && s[4] == 0
        && s[5] == 0) {
        return 2;
    }


    // ============================================
    // 回りたい2
    // ============================================

    if (pairDir == 0
        && s[0] == 2
        && s[1] == 2
        && s[2] == 0
        && s[3] == 0
        && s[4] == 0
        && s[5] == 0
        && s[6] == 2) {
        return 2;
    }

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 0
        && s[4] == 0
        && s[5] == 0
        && s[6] == 2) {
        return 2;
    }


    // ============================================
    // 止めたい
    // ============================================

    if (pairDir == 0
        && s[0] == 2
        && s[1] == 0
        && s[2] == 2
        && (s[3] == 2 || s[3] == 1)
        && s[4] == 2
        && s[5] == 2
        && s[6] == 2) {
        return 6;
    }

    if (pairDir == 0
        && s[0] == 2
        && s[1] == 0
        && s[2] == 2
        && s[3] == 1
        && s[4] == 2
        && s[5] == 2
        && s[6] == 1) {
        return 6;
    }

     if (pairDir == 0
        && s[0] == 2
        && s[1] == 0
        && s[2] == 1
        && s[3] == 2
        && s[4] == 2
        && s[5] == 1
        && s[6] == 2) {
        return 6;
    }



    // ============================================
    // 入りたい
    // ============================================

    if (pairDir == 0
        && s[0] == 2
        && s[1] == 2
        && s[2] == 0
        && s[3] == 0
        && s[4] == 2
        && s[5] == 2
        && s[6] == 0) {
        return 6;
    }

    if (pairDir == 6
        && s[0] == 1
        && s[1] == 2
        && s[2] == 0
        && s[3] == 0
        && s[4] == 2
        && s[5] == 2
        && s[6] == 1) {
        return 6;
    }

    if (pairDir == 6
        && s[0] == 1
        && s[1] == 2
        && s[2] == 2
        && s[3] == 0
        && s[4] == 0
        && s[5] == 2
        && s[6] == 1) {
        return 6;
    }


    // ============================================
    // 戻りたい
    // ============================================

    if (pairDir == 6
        && s[0] == 1
        && s[1] == 1
        && s[2] == 0
        && s[3] == 0
        && s[4] == 0
        && s[5] == 0
        && s[6] == 1) {
        return 6;
    }


    // ============================================
    // 重なりほどきたい
    // ============================================

    if (pairDir == 5
        && s[0] == 2
        && s[4] == 1
        && s[5] == 1) {
        return 5;
    }

    if (pairDir == 5
        && s[0] == 2
        && s[3] == 1
        && s[4] == 2
        && s[5] == 1
        && (s[6] == 1 || s[6] == 2)) {
        return 5;
    }
        //仮
    if (pairDir == 5
        && s[0] == 2
        
        && s[2] == 1
        
        && s[4] == 2
        && s[5] == 1
        && s[6] == 2) {
        return 5;
    }


    // ============================================
    // ブツカリ
    // ============================================

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 0
        && s[2] == 2
        && s[3] == 2
        && s[4] == 0
        && s[5] == 0
        && s[6] == 0) {
        return 2;
    }


    // ============================================
    // 行きたい
    // ============================================

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 0
        && s[4] == 0
        && s[5] == 2
        && s[6] == 2) {
        return 2;
    }

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 0
        && s[4] == 2
        && s[5] == 2
        && s[6] == 0) {
        return 2;
    }

    if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 0
        && s[4] == 0
        && s[5] == 1
        && s[6] == 1) {
        return 2;
    }

     if (pairDir == 2
        && s[0] == 1
        && s[1] == 2
        && s[2] == 1
        && s[3] == 1
        && s[4] == 0
        && s[5] == 0
        && s[6] == 2) {
        return 2;
    }

    return -1;

}
